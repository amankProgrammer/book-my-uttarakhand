const makePackage = ({
  id,
  title,
  category,
  durationDays,
  durationNights,
  startingPrice,
  location,
  image,
  pickupPoint = '',
  meals = '',
  hotelType = '',
  bestSeason = '',
  pricingTiers = [],
  mapQuery = '',
  rating = 4.7,
  featured = false,
  badge = '',
  seatsLeft = 0,
  highlights = [],
  overview = '',
  itinerary = [],
  inclusions = [],
  exclusions = [],
  gallery = [],
}) => ({
  id,
  slug: id,
  title,
  category,
  durationDays,
  durationNights,
  durationLabel: `${durationDays}D/${durationNights}N`,
  startingPrice,
  priceUnit: 'person',
  startingPriceLabel: `₹ ${INR.format(startingPrice)}/person`,
  location,
  image,
  pickupPoint:
    pickupPoint ||
    (category === 'Char Dham & Spiritual Tours'
      ? 'Haridwar / Rishikesh'
      : category === 'Wildlife & Adventure'
        ? 'Ramnagar / Rishikesh'
        : 'Haridwar / Dehradun'),
  meals: meals || 'Breakfast + Dinner',
  hotelType: hotelType || 'Deluxe Hotel',
  bestSeason:
    bestSeason ||
    (category === 'Char Dham & Spiritual Tours'
      ? 'May-Oct'
      : category === 'Wildlife & Adventure'
        ? 'Nov-Jun'
        : category === 'Hill Station & Family Tours'
          ? 'Mar-Jun, Sep-Nov'
          : category === 'Seasonal Packages'
            ? 'Seasonal (check dates)'
            : 'Oct-Mar'),
  pricingTiers:
    pricingTiers.length
      ? pricingTiers
      : [
          { label: 'Standard', price: startingPrice },
          { label: 'Deluxe', price: startingPrice + Math.round(startingPrice * 0.25) },
          { label: 'Luxury', price: startingPrice + Math.round(startingPrice * 0.55) },
        ],
  mapQuery: mapQuery || `${location}, Uttarakhand`,
  rating,
  featured,
  badge,
  seatsLeft,
  highlights,
  overview,
  itinerary,
  inclusions,
  exclusions,
  gallery,
});

